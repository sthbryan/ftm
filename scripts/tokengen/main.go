// Command tokengen turns design/tokens.json into the theme stylesheets the web
// dashboard loads. The token file is the only place a palette value is written;
// the generated CSS is checked in so the build needs no extra step. Run it with
// `make tokens`, and `make tokens-check` to fail on drift.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	tokensPath    = "design/tokens.json"
	themesDir     = "web/src/styles/themes"
	generatedMark = "Code generated by scripts/tokengen from design/tokens.json. DO NOT EDIT."
)

type tokens struct {
	Version int                    `json:"version"`
	Themes  map[string]themeTokens `json:"themes"`
}

type themeTokens struct {
	Mode   string            `json:"mode"`
	Colors map[string]string `json:"colors"`
}

func main() {
	check := flag.Bool("check", false, "verify the generated files are up to date instead of writing them")
	flag.Parse()

	src, err := load(tokensPath)
	if err != nil {
		fail("%v", err)
	}

	outputs := render(src)

	if *check {
		if stale := staleOutputs(outputs); len(stale) > 0 {
			fmt.Fprintf(os.Stderr, "generated themes are stale, run `make tokens`:\n  %s\n", strings.Join(stale, "\n  "))
			os.Exit(1)
		}
		return
	}

	for path, body := range outputs {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			fail("create %s: %v", filepath.Dir(path), err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			fail("write %s: %v", path, err)
		}
	}

	fmt.Printf("tokens: wrote %d theme files\n", len(outputs))
}

func load(path string) (*tokens, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}

	var src tokens
	if err := json.Unmarshal(data, &src); err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}
	if src.Version != 1 {
		return nil, fmt.Errorf("%s has version %d, want 1", path, src.Version)
	}
	if len(src.Themes) == 0 {
		return nil, fmt.Errorf("%s defines no themes", path)
	}

	return &src, validate(&src)
}

// validate fails the generation instead of emitting a theme that is missing a
// token, which is how a palette silently breaks at runtime.
func validate(src *tokens) error {
	reference := map[string]string{}

	for _, name := range themeNames(src) {
		theme := src.Themes[name]

		switch theme.Mode {
		case "dark", "light":
		default:
			return fmt.Errorf("theme %q has mode %q, want dark or light", name, theme.Mode)
		}

		if len(reference) == 0 {
			reference = theme.Colors
			continue
		}

		for token := range reference {
			if _, ok := theme.Colors[token]; !ok {
				return fmt.Errorf("theme %q is missing %s", name, token)
			}
		}
		for token := range theme.Colors {
			if _, ok := reference[token]; !ok {
				return fmt.Errorf("theme %q defines unknown token %s", name, token)
			}
		}
	}

	return nil
}

func themeNames(src *tokens) []string {
	names := make([]string, 0, len(src.Themes))
	for name := range src.Themes {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func render(src *tokens) map[string]string {
	outputs := make(map[string]string, len(src.Themes))

	for _, name := range themeNames(src) {
		path := filepath.Join(themesDir, "_"+name+".css")
		outputs[path] = renderTheme(name, src.Themes[name])
	}

	return outputs
}

func renderTheme(name string, theme themeTokens) string {
	var b strings.Builder

	b.WriteString("/* " + generatedMark + " */\n\n")
	fmt.Fprintf(&b, "[data-theme=%q] {\n", name)

	for _, token := range sortedTokens(theme.Colors) {
		fmt.Fprintf(&b, "  %s: %s;\n", token, theme.Colors[token])
	}

	b.WriteString("}\n")
	return b.String()
}

func sortedTokens(colors map[string]string) []string {
	names := make([]string, 0, len(colors))
	for token := range colors {
		names = append(names, token)
	}
	// bg first keeps the block readable.
	sort.Slice(names, func(i, j int) bool {
		if ri, rj := tokenRank(names[i]), tokenRank(names[j]); ri != rj {
			return ri < rj
		}
		return names[i] < names[j]
	})
	return names
}

func tokenRank(token string) int {
	if token == "--color-bg" {
		return 0
	}
	return 1
}

func staleOutputs(outputs map[string]string) []string {
	var stale []string

	for path, want := range outputs {
		got, err := os.ReadFile(path)
		if err != nil || string(got) != want {
			stale = append(stale, path)
		}
	}

	sort.Strings(stale)
	return stale
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "tokengen: "+format+"\n", args...)
	os.Exit(1)
}
